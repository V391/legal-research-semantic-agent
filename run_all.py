"""End to end, and the definition of done: exits non-zero if any step falls short.

1. generate the business and its answer key          generator/generate.py
2. land bronze, build silver and gold, run every test  load_raw.py + dbt build (answer key tests included)
3. docs gate                                            checks/check_docs.py
4. Power BI model from the same definitions             semantic/export_tmdl.py
5. agent evaluation (replays recorded model answers)    eval/run_eval.py
6. renewal risk and usage anomaly models                ml/
7. injected defects, production tests only              checks/inject_defects.py
8. reports/results.md
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ENV = {**os.environ, "DBT_PROFILES_DIR": str(ROOT), "PYTHONIOENCODING": "utf-8"}


def step(*args: str) -> None:
    print(f"$ {' '.join(args)}", flush=True)
    r = subprocess.run(args, cwd=ROOT, env=ENV)
    if r.returncode:
        sys.exit(r.returncode)


def dbt() -> str:
    scripts = Path(sys.executable).parent
    return next((str(scripts / n) for n in ("dbt.exe", "dbt") if (scripts / n).exists()), "dbt")


def main() -> None:
    py = sys.executable
    step(py, "generator/generate.py")
    step(py, "load_raw.py")
    step(dbt(), "build")
    step(py, "checks/check_docs.py")
    step(py, "semantic/export_tmdl.py")
    step(py, "eval/run_eval.py")
    step(py, "ml/renewal_risk.py")
    step(py, "ml/usage_anomalies.py")
    step(py, "checks/inject_defects.py")
    write_results()


def write_results() -> None:
    import duckdb

    con = duckdb.connect(str(ROOT / "warehouse" / "dev.duckdb"), read_only=True)
    q = lambda s: con.execute(s).fetchone()  # noqa: E731
    rows = q("select (select count(*) from gold.fct_arr_monthly), (select count(*) from gold.fct_renewals), "
             "(select count(*) from gold.fct_usage_weekly), (select count(*) from gold.dim_firm), "
             "(select count(distinct account_id) from gold.dim_firm)")
    arr24, arr25 = q("select sum(arr_usd) filter (where month_end = date '2024-12-31'), "
                     "sum(arr_usd) filter (where month_end = date '2025-12-31') from gold.fct_arr_monthly")
    ev = json.loads((ROOT / "eval" / "runs" / "summary.json").read_text())
    rr = json.loads((ROOT / "reports" / "renewal_risk.json").read_text())
    an = json.loads((ROOT / "reports" / "usage_anomalies.json").read_text())
    df = json.loads((ROOT / "reports" / "defects.json").read_text())
    g, b = ev["governed"], ev["baseline"]
    d, s = an["detector_seasonal_robust_z"]["test_2025"], an["baseline_static_threshold"]["test_2025"]
    md = f"""# Results

Generated by `python run_all.py`. Every number below is recomputed on each run.

## Warehouse
| | |
|---|---|
| Customer firms | {rows[4]:,} ({rows[3]:,} Type 2 versions) |
| ARR snapshot rows (firm x product x month end) | {rows[0]:,} |
| Renewal decisions | {rows[1]:,} |
| Usage rows (firm x product x week) | {rows[2]:,} |
| ARR Dec 2024 / Dec 2025 | ${arr24:,.0f} / ${arr25:,.0f} |
| Gold tables matching the answer key | 5 of 5, every row |
| Injected defects caught by production tests | {df['caught']} of {df['total']} |

## Agent evaluation ({g['questions']} questions x {g['runs']} runs, same model)
| | Governed (semantic layer) | Text-to-SQL (documented star schema) |
|---|---|---|
| Correct answers | {g['correct']}/{g['answers']} ({g['accuracy']:.0%}) | {b['correct']}/{b['answers']} ({b['accuracy']:.1%}) |
| Questions right on every run | {g['questions_right_every_run']}/{g['questions']} | {b['questions_right_every_run']}/{b['questions']} |
| Questions whose answer changed between runs | {g['questions_right_some_runs_only']} | {b['questions_right_some_runs_only']} |
| Wrong answers that ran without error | {g['executed_but_wrong']} | {b['executed_but_wrong']} |

## Renewal risk (out of time: train before Jul 2025, test Jul to Dec 2025)
| | AUC | Churned ARR in riskiest 20% |
|---|---|---|
| Rule: lowest seat utilization | {rr['test_auc_rule_low_utilization']:.2f} | {rr['churned_arr_in_top20pct_rule']:.0%} |
| Model chosen by grouped CV ({rr['chosen']}) | {rr['test_auc_model']:.2f} | {rr['churned_arr_in_top20pct_model']:.0%} |

Decision: ship the **{rr['ship']}**.

## Usage anomalies (thresholds tuned on 2024, scored on 2025)
| | Flagged | Precision | Recall |
|---|---|---|---|
| Static threshold | {s['flagged']:,} | {s['precision']:.1%} | {s['recall']:.0%} |
| Seasonal robust z | {d['flagged']:,} | {d['precision']:.0%} | {d['recall']:.0%} |
"""
    (ROOT / "reports" / "results.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    if sys.argv[1:] == ["--report"]:
        write_results()
    else:
        main()
